/**
 * Groups for the odd-one-out game (DRAFT for review, 2026-11-15).
 *
 * A question shows three emojis from one group and one that is not in
 * it. 💡 shows the group's phrase ("Tre av dem bor på bondgården"), and
 * after answering the scene explains it: "🐄 🐖 🐑 bor på bondgården,
 * men inte 🦁." So `sv`/`en` are phrases that follow "Tre av dem" /
 * "Three of them".
 *
 * Levels:
 * - 'far': what kind of thing it is. The odd one is another kind
 *   (three animals and a food).
 * - 'close': a group inside a kind (`in`). The odd one is the same kind
 *   but not in the group (three farm animals and a lion).
 * - 'trait': a property (color, wings, size). The odd one comes from the
 *   groups in `in`. Colors (`color: true`) are judged among every emoji
 *   that has a color tag.
 *
 * Each emoji below lists every group it is in, so a line can be checked
 * on its own. A tag with "?" means "could be argued either way": the
 * emoji is never drawn with that group, neither as one of the three nor
 * as the odd one, and the game rejects any question where that doubt
 * could make a second right answer. Groups can also list doubtful groups
 * in `unsure` (birds are "in the sky" for some kids).
 *
 * The game also rejects a question when some other group holds exactly
 * three of the four and leaves out a different one (🍎 🍓 🌹 are red,
 * 🍌 isn't, but 🍎 🍓 🍌 are fruit, so 🌹 would be right too).
 *
 * Colors are only tagged where the emoji has that color on both iPhone
 * and Android.
 */

